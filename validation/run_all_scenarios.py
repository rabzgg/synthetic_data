"""
run_all_scenarios.py — every required scenario on five seeds, through the generator and the gate;
writes docs/GATE_RESULTS.md (the summary) and keeps the files in --out (not in the repository).

Usage: python3 validation/run_all_scenarios.py [--out out/all] [--seeds 42 43 44 45 46]
"""
import argparse
import json
import os
import sys
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from core.output import run

SCENARIOS = ["gas_normal_shift", "gas_stel_alarm", "gas_twa_alarm", "gas_over_range", "gas_voc_exposure",
             "gas_pump_fault", "worker_collapse", "fridge_compressor_failure", "pump_bearing_wear", "field_irrigation",
             "water_tank_leak", "server_room_ac_failure"]
DOC = os.path.join(ROOT, "docs", "GATE_RESULTS.md")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(ROOT, "out", "all"))
    ap.add_argument("--seeds", type=int, nargs="*", default=[42, 43, 44, 45, 46])
    args = ap.parse_args()
    rows, n_pass, n = [], 0, 0
    for sc in SCENARIOS:
        for seed in args.seeds:
            t0 = time.time()
            for r in run(sc, seed=seed, out_dir=os.path.join(args.out, sc)):
                g = json.load(open(r["gate"]))
                n += 1
                n_pass += g["passed"]
                rows.append((sc, seed, r["device"], g["passed"], len(g["checks"]), ", ".join(g["failed"])))
                print(f"{sc:28s} seed {seed} {r['device']:22s} {'PASS' if g['passed'] else 'FAIL'} "
                      f"{time.time() - t0:5.1f} s {g['failed']}")
    L = ["# Gate results", "",
         "_Generated by `python3 validation/run_all_scenarios.py`; do not edit by hand._", "",
         f"**{n_pass} of {n} device files pass their gate** ({len(SCENARIOS)} scenarios × seeds "
         f"{', '.join(map(str, args.seeds))}). The gate (`validation/auto_gate.py`) is derived from each device's spec "
         "and recomputes everything it can from the CSV; what it checks is listed at the top of that file.", "",
         "| scenario | seed | device | gate | checks | failed |", "|---|---|---|---|---|---|"]
    L += [f"| `{sc}` | {seed} | `{dev}` | {'PASS' if ok else '**FAIL**'} | {k} | {f or '—'} |" for sc, seed, dev, ok, k, f in rows]
    with open(DOC, "w") as fh:
        fh.write("\n".join(L) + "\n")
    print(f"{n_pass}/{n} pass; wrote {os.path.relpath(DOC, ROOT)}")
    sys.exit(0 if n_pass == n else 1)


if __name__ == "__main__":
    main()
