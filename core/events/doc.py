"""
doc.py — docs/EVENTS.md, generated from the event classes, the scenario files and the device presets
(python3 cli/events_doc.py). Never edited by hand.
"""
import os

from .scenario import EVENTS, compatibility, list_scenarios, load_scenario

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DOC = os.path.join(ROOT, "docs", "EVENTS.md")


def _cell(x):
    return str(x).replace("|", "\\|").replace("\n", " ")


def _table(rows, slugs):
    L = ["| event | " + " | ".join(f"`{s}`" for s in slugs) + " |", "|---|" + "---|" * len(slugs)]
    whys = {}
    for name, cells in rows:
        out = []
        for s in slugs:
            ok, why = cells[s]
            if ok:
                out.append("✓")
            else:
                k = whys.setdefault(why, len(whys) + 1)
                out.append(f"– ({k})")
        L.append(f"| {name} | " + " | ".join(out) + " |")
    L += [""] + [f"({k}) {why}" + "  " for why, k in whys.items()]
    return L


def markdown() -> str:
    from core.devices import list_devices
    slugs = list_devices()
    L = ["# Events and scenarios", "",
         "_Generated by `python3 cli/events_doc.py` from `configs/events/`, `configs/scenarios/` and `configs/devices/`; "
         "do not edit by hand._", "",
         "An event changes the world (its drivers or the body's motion; the world then derives RH, O2, pressure and the "
         "body tracks again) or one device (what its sensors are given, its states, its connection). It never writes a "
         "CSV column. Events are data (`configs/events/*.yaml`, format in `core/events/library.py`). A world event is "
         "seen by a device when it changes something the device measures, at its mount, by at least that sensor's "
         "resolution (tried numerically); a device event when the device has the features it needs and measures what "
         "it is given. An event no device of a run can see is refused with the reason. Building blocks are small "
         "events meant for composites.", "",
         "## Events", ""]
    for kind, cls in [(k, c) for k, c in EVENTS.items() if not c.building_block] + \
            [(k, c) for k, c in EVENTS.items() if c.building_block]:
        e = cls(0.0)
        reach = "devices worn on the body" if cls.body else ("the device it is given to" if cls.scope == "device" else
                                                              "every device that measures what it affects")
        L += [f"### `{kind}`: {cls.name}" + (" (building block)" if cls.building_block else ""), "",
              cls.description, ""]
        if cls.steps:
            L.append(f"- Composite: {' → '.join(f'`{s_}`' for s_ in (st['event'] for st in cls.steps))}.")
        L += [f"- Changes: {'one device' if cls.scope == 'device' else 'the world'}; reaches {reach}."]
        if e.affects():
            L.append(f"- Affects: {', '.join(f'`{a}`' for a in e.affects())}" +
                     (" (with the default gas)" if "gas" in cls.PARAMS else ""))
        if e.requires():
            L.append(f"- Needs the device feature: {', '.join(f'`{r}`' for r in e.requires())}")
        afters = sorted({ef.get("after", "revert") for ef in cls.effects if ef.get("target") != "motion"})
        if afters:
            L.append("- After the event: " + " / ".join(
                {"revert": "`revert` (goes back)", "hold": "`hold` (stays as reached)"}[a] for a in afters))
        L += ["", "| parameter | default | unit | source |", "|---|---|---|---|"]
        for k, p in cls.PARAMS.items():
            L.append(f"| `{k}` | {_cell(p['value'])} | {_cell(p['unit'])} | {_cell(p['source'])} |")
        L.append("")
    L += ["## What the labels say", "",
          "Each run writes, per device, the events it saw (scope `world` or `device`) and what the device should do "
          "in response (scope `expected`):", "",
          "- **No motion** (logic block `stillness_timer`, column e.g. `no_motion_state`): after `detect_s` without "
          "movement (measured over `window_s`) a `no_motion_pre_alarm` for `pre_alarm_s`, then a `no_motion_alert`, "
          "until the body moves again.",
          "- **Fall** (logic block `spike_then_still`, e.g. `fall_state`): an impact of at least `spike_g` followed by a "
          "tilt of at least `tilt_deg` gives a `fall_pre_alarm` for `pre_alarm_s`; getting up within it cancels it, "
          "otherwise a `fall_alert` until upright again.",
          "- The expected labels come from running the device's own blocks on the world's truth (no sensor errors); "
          "the gate compares the device's column with them.",
          "- **Collapse**: `collapse:gas_release` → `collapse:fall` → `collapse:stir` (moves a little, "
          "`no_motion_after_s`) → `collapse:no_motion` (`no_motion_s`) → `collapse:rescue`; the gaps are parameters.",
          "", "## Which device sees which event", "",
          "Device presets with default event parameters. Gas releases at the default level (20 ppm or 20 %LEL); a "
          "device sees one if it measures the gas, or if the O2 drop it causes reaches its O2 resolution.", "",
          "### Worn on the body", ""]
    L += _table(compatibility(slugs, "body"), slugs)
    L += ["", "### Fixed (wall, shelf, post)", ""]
    L += _table(compatibility(slugs, "fixed"), slugs)
    L += ["", "## Scenarios", "", "| scenario | title | world | devices | events |", "|---|---|---|---|---|"]
    for name in list_scenarios():
        sc = load_scenario(name)
        devs = ", ".join(f"`{d['device']}` ({d.get('mount', 'body')})" for d in sc.get("devices", []))
        evs = ", ".join(next(iter(e)) for e in sc.get("events", []))
        L.append(f"| `{name}` | {_cell(sc.get('title', ''))} | `{sc['world']}` | {devs} | {evs} |")
    return "\n".join(L) + "\n"
