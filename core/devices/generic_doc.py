"""
generic_doc.py — the table of generic parts in docs/PRESALES.md, generated from configs/parts/ (one row
per quantity, in catalog order). Written between two markers by python3 cli/update_docs.py and never
edited by hand; tests/test_generic_parts.py checks that it is up to date.
"""
import os

from core.quantities import CATALOG

from .parts import PARTS_DIR, Part, generic_parts, parts_measuring

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DOC = os.path.join(ROOT, "docs", "PRESALES.md")
BEGIN = "<!-- generic table: generated by python3 cli/update_docs.py from configs/parts/, do not edit by hand -->"
END = "<!-- end of generic table -->"
VERIFY = "[USER TO VERIFY]"


def _g(x) -> str:
    x = float(x)
    return str(int(x)) if x.is_integer() and abs(x) < 1e12 else f"{x:.4g}"


def _range(m, unit) -> str:
    lo, hi = m.range
    return f"{_g(lo)} to {_g(hi)} {unit}"


def _t90(m) -> str:
    s = f"{_g(m.t90_s)} s"
    extra = [f"{k} {_g(v)}" for k, v in (("up", m.t90_up_s), ("down", m.t90_down_s)) if v is not None]
    return s + (f" ({', '.join(extra)})" if extra else "")


def _odr(m) -> str:
    if m.odr_range_hz:
        lo, hi = m.odr_range_hz
        return f"{_g(m.odr_hz)} Hz, follows the sample rate within {_g(lo)} to {_g(hi)} Hz"
    return f"{_g(m.odr_hz)} Hz (fixed)"


def _accuracy(m, unit) -> str:
    sigma = lambda k: " (1σ)" if m.kinds.get(k) == "typical" else ""
    parts = []
    if m.accuracy:
        parts.append(f"±{_g(m.accuracy)} {unit}{sigma('accuracy')}")
    if m.accuracy_pct_reading:
        parts.append(f"±{_g(m.accuracy_pct_reading)} % of reading{sigma('accuracy_pct_reading')}")
    if not parts:
        return "none"
    return " + ".join(parts) if m.accuracy_combine == "sum" else " or ".join(parts) + ", whichever is greater"


def _anchor(q, parts_dir) -> str:
    named = parts_measuring(q, parts_dir)
    if not named:
        return "class typical (no datasheet part in the repo)"
    unverified = [s for s in named if VERIFY in Part.load(s, parts_dir).datasheet]
    text = "not better than " + ", ".join(f"`{s}`" for s in named)
    return text + "".join(f" (`{s}` is still {VERIFY})" for s in unverified)


def table(parts_dir: str = PARTS_DIR) -> str:
    g = generic_parts(parts_dir)
    rows = ["| quantity | column | part | class | range | resolution | noise sd (at the default ODR) | t90 | ODR | "
            "accuracy | anchored on |",
            "|---|---|---|---|---|---|---|---|---|---|---|"]
    for q, quantity in CATALOG.items():
        if q not in g:
            continue
        slug = g[q][0]
        p = Part.load(slug, parts_dir)
        m, unit = p.models()[q], quantity.unit
        col = quantity.column.replace("{axis}", "{x,y,z}")
        rows.append(f"| `{q}` | `{col}` | `{slug}` | {p.cls} | {_range(m, unit)} | {_g(m.resolution)} {unit} | "
                    f"{_g(m.noise_sd)} {unit} | {_t90(m)} | {_odr(m)} | {_accuracy(m, unit)} | {_anchor(q, parts_dir)} |")
    return "\n".join(rows) + "\n"


def markdown(text: str = None, parts_dir: str = PARTS_DIR) -> str:
    """docs/PRESALES.md with the generic table between the markers replaced by a fresh one."""
    if text is None:
        with open(DOC) as fh:
            text = fh.read()
    head, sep, rest = text.partition(BEGIN)
    if not sep or END not in rest:
        raise ValueError(f"{DOC}: the markers of the generic table are missing")
    return head + BEGIN + "\n" + table(parts_dir) + END + rest.split(END, 1)[1]
